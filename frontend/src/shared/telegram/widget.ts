/**
 * Telegram's current Login Widget (https://core.telegram.org/bots/
 * telegram-login) — OIDC-based, replacing the legacy HMAC-signed-fields
 * widget (archived at /widgets/login-legacy). That legacy widget is what
 * this file originally embedded; it was swapped out after Telegram started
 * rejecting it with "Bot domain invalid" for a bot whose domain is
 * registered through @BotFather's current "Login Widget" panel (Client
 * ID/Secret, Allowed URLs) rather than the old `/setdomain` command — the
 * two registration mechanisms aren't interchangeable.
 */

export interface TelegramWidgetAuthResult {
  id_token?: string
  error?: string
}

let callbackCounter = 0

/**
 * Embeds Telegram's Login Widget into `container`. Like the legacy widget,
 * this is Telegram's own `<script>` embed (generated by the tool at
 * https://core.telegram.org/bots/telegram-login) rather than a function
 * call off a pre-loaded library — it scans the DOM for a sibling
 * `.tg-auth-button` element and wires it up once loaded. `onAuth` fires
 * with the widget's raw result (`{id_token}` on success, `{error}` on
 * failure); the caller is responsible for checking which. Nothing here is
 * trusted client-side — `id_token` is a signed JWT the backend verifies
 * itself (`POST /auth/telegram/widget`) against Telegram's public keys.
 */
export function mountTelegramLoginWidget(
  container: HTMLElement,
  botClientId: number,
  onAuth: (result: TelegramWidgetAuthResult) => void,
): void {
  const callbackName = `tgLoginCallback_${callbackCounter++}`
  ;(window as unknown as Record<string, (result: TelegramWidgetAuthResult) => void>)[
    callbackName
  ] = onAuth

  container.innerHTML = ''

  const script = document.createElement('script')
  script.async = true
  script.src = 'https://oauth.telegram.org/js/telegram-login.js?6'
  script.setAttribute('data-client-id', String(botClientId))
  script.setAttribute('data-onauth', `${callbackName}(user)`)

  const button = document.createElement('button')
  button.className = 'tg-auth-button'
  button.textContent = 'Sign In with Telegram'

  container.appendChild(script)
  container.appendChild(button)
}
